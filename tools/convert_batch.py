def conv(src_file="batch_in.json", category="yojijukugo", categoryName="四字熟語"):
    src = json.load(open(src_file, encoding='utf-8'))
    items = json.load(open('items.json', encoding='utf-8'))
    n = 0
    for it in src:
        sub = it["category"]
        opts = it["choices"]
        ai = opts.index(it["answer"])
        word = it.get("full_word") or it["question"].split("（")[0]
        yomi = YOMI.get(word) or ""
        if sub.startswith("漢字穴埋め"):
            q = f"（　）に入る漢字を選びなさい。\n「{it['question']}」"
            ex = f"正解は「{it['answer']}」で「{word}（{yomi}）」と書きます。" if yomi else f"正解は「{it['answer']}」で「{word}」と書きます。"
        elif sub == "意味選択":
            q = f"「{it['question']}」の意味として正しいものを選びなさい。"
            ex = f"「{word}（{yomi}）」{it['answer']}" if yomi else it["answer"]
        else:
            q = it["question"]
            w2 = it["answer"]
            y2 = YOMI.get(w2) or ""
            if y2:
                ex = f"正解は「{w2}（{y2}）」です。"
            else:
                quoted = re.findall(r"「(.+?)」", it["question"])
                ty = quoted and YOMI.get(quoted[0]) or ""
                if ty:
                    ex = f"「{quoted[0]}（{ty}）」{w2}"
                else:
                    ex = f"正解は「{w2}」です。"
        items.append({
            "id": f"yoji_{it['id']}",
            "category": category,
            "categoryName": categoryName,
            "subCategory": sub,
            "question": q,
            "options": opts,
            "answerIndex": ai,
            "explanation": ex
        })
        n += 1
    json.dump(items, open('items.json','w',encoding='utf-8'), ensure_ascii=False, indent=2)
    print("added", n, "total", len(items))

if __name__ == "__main__":
    conv()
